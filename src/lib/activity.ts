// Actions about one AI employee, phrased with its name when the audit row identifies it.
const AGENT_LABELS: Record<string, (name: string) => string> = {
  "agent.config_version_created": (n) => `updated the ${n}'s configuration`,
  "agent.config_review_approved": (n) => `iAcquire approved a held ${n} configuration`,
  "agent.config_review_rejected": (n) => `iAcquire declined a held ${n} configuration`,
  "agent.hermes_connected": (n) => `connected the ${n}'s dedicated environment`,
  "agent.enabled": (n) => `enabled the ${n}`,
  "agent.disabled": (n) => `disabled the ${n}`,
};

export function describeAction(action: string, agentName?: string | null): string {
  if (agentName && AGENT_LABELS[action]) return AGENT_LABELS[action](agentName);
  return LABELS[action] ?? action.replace(/[._]/g, " ");
}
